# -1.출근한 직원의 이름을 리스트에 저장한다.
# -2.관리자가 확인할 직원의 이름을 입력한다.
#  -3.입력할 이름이 리스트에 있는지 확인한다.
#  -4.있다면 직원의 위치를 번호를 찾아 출력한다.
#  -5.없다면 출근하지 않았습니다.
오늘출근직원 = ["민수", "지영", "철수", "수빈", "영희"]
직원이름 = input("직원 이름을 입력하세요:")
if 직원이름 in 오늘출근직원:
    print("출근확인!",오늘출근직원.index(직원이름))
else :
    print("출근 기록이 없습니다!")
# --------------------------------------------------튜터님답 밑에
출근명단 =  ["민수", "지영", "철수", "수빈", "영희"]

이름 = input("검색할 직원명:")

if 이름 in 출근명단:
    print("출근확인")
    print(출근명단.index(이름)+1,"번째 출근함")
else:
    print("노 출근!")
# 여기서 +1하는 이유는 민수가 원래 0인데 1로 만들기 위해서(뇌피셜)