# 1.앱이 저장해 둔것은?
# RPG 게임 가방은 5칸이에요.
# 2.앱이 하는 일을 순서대로 작성?
#  -1.게임 가방 5칸을 저장한다.
#  -2.아이템 이름을 입력받아 줍는다
#  -3.5칸이 찰때까지 반복한다.
#  -4.줍는 아이템이 포션이면 특별안내를 띄운다.
#  -5.다 차면 가방 내용을 보여준다.
# 3.몇번째 값을 꺼내나? 어디서부터 어디까지 짜르나?
#
게임가방 =[]
# 아이템 = input("아이템 이름을 입력하시오:")
# 게임가방.append(아이템)
게임가방칸 = len(게임가방)

while 게임가방칸 < 5:
    아이템 = input("아이템 이름을 입력하시오:")
    게임가방.append(아이템)
    게임가방칸 = len(게임가방)

    if 아이템 == "포션":
        print("특별한 아이템 입니다!")
        break

    elif 게임가방칸 == 5:
        print(게임가방)
