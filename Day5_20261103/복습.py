# 검색기록
# 검색창에 단어를 검색할때마다 기록이 쌓입니다.
# 맨 위에는 가장 최근에 검색한 단어가 표시됩니다.
# 오늘 검색한 단어는 "파이썬", "리스트","슬라이싱",
# "append" 순서입니다. (새 검색어는 기록의 맨 뒤에 붙는다고 약속해요.)

# 1. 앱이 저장해 둔것은?
# 오늘 검색한 단어 "파이썬", "리스트","슬라이싱","append"
# 2.앱이 하는일을 순서대로?
#   -1.검색한 단어를 리스트에 저장한다.
#   -2.리스트에서 최근 검색어 3개를 꺼낸다.
#   -3.최근 검색어 3개의 순서를 뒤집는다.
#   -4.가장 최근 검색어를 맨위에 보여준다.
#   -5.나머지는 검색어를 차례대로 보여준다.

# 3.몇번째 값을 꺼내나? / 어디서부터 어디까지 자르나?
#  마지막 3개를 꺼내고 순서를 뒤집다.

#1. 저장한 검색어 목록
검색기록 = ["파이썬", "리스트","슬라이싱","append"]

#2. 뒤에서 3개를 뽑기
결과 = 검색기록[-3:]  #뒤에서부터 -1,-2,-3으로감 앞은 0,1,2..

# 3개뽑은결과가 뒤집어져야함
# 3.리스트가 제공하는 기능을 쓸때는
# !!! print(),변수 !!!안에 넣으면 안된다.
# 뒤집는 기능은 실행하고 결과를 알려주지 않는다. 뒤집은결과는 자동으로 저장하기 때문에 
# 따로 변수에 저장할 필요가 없다!  (아직 함수가 들어가지 않았으니,,,쉽게,,)
결과.reverse()
print(결과)

# 3.가장 마지막에 검색한 단어 출력
가장마지막 = 검색기록[-1]
print(가장마지막)  #검색어는 항상 뒤에서 붙기때문

