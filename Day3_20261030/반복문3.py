# 반복문3.py
# 비밀번호가 맞을때까지 반복하세요 while True
# 틀린횟수가 5번 되면 역시 마찬가지로 
# 반복을 멈춘다.

틀린횟수 = 0

while True:

    비번 = int(input("비밀번호"))
    
    if 비번 == 1234 :
        print("비번이 맞았습니다.")
        break #무한반복을 멈출때 사용!
    elif 틀린횟수 ==5:
        print("10분 뒤 다시 실행하세요")
        break
    else:
        print("비밀번호 다시 입력하세요")
        틀린횟수 = 틀린횟수 + 1
        print("틀린횟수:",틀린횟수)

