# 실습 문제: 쿠폰 코드 입력 프로그램


# 상황 설명여러분이 온라인 쇼핑몰에서 옷을 구매하려고 합니다.

# 쇼핑몰에서 할인 쿠폰 번호 1234를 발급했습니다.

# 쿠폰 번호를 입력하면 할인을 받을 수 있지만, 입력 기회는 최대 5번입니다.
# 2. 프로그램 요구사항

# 사용자에게 쿠폰 번호를 입력받으세요.
# 쿠폰 번호가 1234이면 "쿠폰 적용 성공! 10% 할인"을 출력하세요.
# 쿠폰 번호가 틀리면 다시 입력받으세요.
# 최대 5번까지만 입력할 수 있습니다.
# 5번 모두 틀리면 "쿠폰 입력 횟수 초과!"를 출력하세요.
틀린횟수 = 0
while True:
    쿠폰번호 = int(input("쿠폰번호"))

    if 쿠폰번호 ==1234:
        print("쿠폰 적용 성공! 10% 할인")
        break
    elif 틀린횟수 == 5:
        print("쿠폰 입력 횟수 초과!")
        break
    else :
        print("쿠폰번호를 다시 입력하세오.")
        틀린횟수 = 틀린횟수 + 1
        print("틀린횟수:",틀린횟수)