# 온라인 강의 들을 때 수강률

수강률 = 0.8

print("현재 달성률:", 수강률)

# :.1%
# : 출력할때 모양 지정한다
# .1 - 소수점 아래 1자리
# % - 100을 곱해 백분율 표시하고
# %를 붙인다.
print(f"현재 달성률: {수강률:.1%}")
