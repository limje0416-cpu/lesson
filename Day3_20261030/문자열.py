# 평균을 계산하고 출력하는 프로그램!
# 1. 점수를 입력받는다
국어 =int(input("국어:"))
수학 =int(input("수학:"))
영어 =int(input("영어:"))

# 2. 더하기 
더한결과 = 국어 + 수학 + 영어

# 3. 나누기 (과목수!)
평균 = 더한결과 / 3

# 4. 결과 출력!
print(f"평균: {평균}")
#자리수를 지정하는 형식!

#{평균:.3f}
# - 평균값을 출력할때 소수점
#   자리를 정한다
print(f"평균: {평균:.5f}")

# 쇼핑몰 금액 출력 천단위로 , 붙는것!
