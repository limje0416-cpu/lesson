def 운임비(목적지):
    목적지별 ={
        "춘천":5000,
        "부산":30000,
        "대구":2000,
        "수원":10000,
    }
    
    if 목적지 not in 목적지별:
        print("없는데! 다른데 입력해!")
    else:
        print(목적지,목적지별[목적지])
        
