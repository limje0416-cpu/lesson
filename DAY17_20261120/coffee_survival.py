# 1. 어떤 서비스 인가요? (한 줄 목적)
#  - 어제 잔 시간(수면)과 오늘 남은 할 일(업무/공부) 시간을 입력하면, 
#    아메리카노를 마셔야 버틸 수 있을지 글자와 확률로 알려준다.

# 2. 누가 사용하나요?
#  - 피곤한 직장인, 시험 기간 학생 등 오늘 커피 수혈이 필요한지 고민하는 사람

# 3. 사용자는 어떻게 사용하나요?
#  - 1. 어제 밤 수면 시간(0~12시간)을 입력한다.
#  - 2. 오늘 남은 업무/공부 시간(0~12시간)을 입력한다.
#  - 3. '카페인 수혈 필요할까?' 버튼을 누른다.
#  - 4. 커피가 필요한 확률과 상태별 행동 지침을 확인한다.

# 4. 어떤 데이터로 학습하나요?
#  - 과거의 [수면 시간, 남은 할 일 시간]과 그날의 실제 상태("커피필수", "버틸만함") 데이터를 사용한다.

import streamlit as st
from sklearn.linear_model import LogisticRegression

# ---- 과거 기록 (학습 데이터) ----
# 형태: [[수면시간, 남은_할일_시간], ...]
데이터 = [
    [3, 9], [4, 8], [4, 7], [5, 8], [5, 6],   # 잠 적고 일 많음 -> 커피 필수
    [7, 3], [8, 4], [8, 2], [9, 2], [7, 1]    # 잠 많고 일 적음 -> 버틸만함
]
상태 = [
    "커피필수", "커피필수", "커피필수", "커피필수", "커피필수",
    "버틸만함", "버틸만함", "버틸만함", "버틸만함", "버틸만함"
]

# ---- 화면 구성 ----
st.title("☕ 직장인/학생 생존 예측: 아메리카노 몇 잔 각?")
st.write("어제 수면 시간과 오늘 남은 일정을 알려주시면 카페인 수혈 필요성을 예측해 드립니다.")

# 두 개의 입력을 나란히 배치

수면시간 = st.number_input("어제 몇 시간 잤나요? (시간)", min_value=0, max_value=12, value=6)
남은일 = st.number_input("남은 업무/공부 시간은? (시간)", min_value=0, max_value=12, value=5)

# ---- 모델 학습 ----
모델 = LogisticRegression()
모델.fit(데이터, 상태)

# ---- 예측 및 결과 출력 ----
if st.button("카페인 수혈 필요할까? 🔍"):
    결과 = 모델.predict([[수면시간, 남은일]])
    확률 = 모델.predict_proba([[수면시간, 남은일]])
    
    # "커피필수"가 몇 번째 칸인지 찾아 확률 추출
    커피칸 = list(모델.classes_).index("커피필수")
    커피확률 = float(확률[0][커피칸])

    st.divider() # 구분선

    # 1. 예상 행동 출력
    if 결과[0] == "커피필수":
        st.subheader("🚨 지금은 아메리카노 수혈이 시급합니다!")
    else:
        st.subheader("🌿 아직은 맨정신으로 버틸 수 있어요!")

    # 2. 확률 출력
    st.write(f"커피가 필요할 확률: **{round(커피확률 * 100)}%**")

    # 3. 확률 3단계 상태 안내
    # 30% 미만: 여유로움 (success)
    # 30% 이상 ~ 70% 미만: 1잔 권장 (warning)
    # 70% 이상: 2잔 이상 또는 사약(샷추가) 필수 (error)
    if 커피확률 >= 0.7:
        st.error("💀 경고: 아이스 아메리카노 샷 추가(투샷 이상)가 시급합니다! 당장 카페로 가세요!")
    elif 커피확률 >= 0.3:
        st.warning("☕ 주의: 슬슬 눈이 감길 시간입니다. 따뜻한/아이스 아메리카노 1잔을 추천합니다.")
    else:
        st.success("💪 양호: 컨디션이 좋네요! 커피 대신 물 한 잔으로도 충분합니다.")