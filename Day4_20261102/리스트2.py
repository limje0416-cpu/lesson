# 비어있는 바구니! 하나가 생긴다.
장바구니 = []
print(장바구니)

# len은 사이즈,개수를 구하는 기능 내가 예약한것 !
장바구니개수 = len(장바구니)
print("현재개수:",장바구니개수)

# 담기 버튼을 클릭했다는 가정하에 데이터를 추가 하는 기능
# 이거는 리스트가 가지고있는 기능 비어있는 변수를 만들고 거기에 데이터를 추가하겠다는것!
장바구니.append("미역국")
장바구니.append("가글")
print(장바구니)

장바구니개수 = len(장바구니) #이렇게 추가한번더 해줘야됨!
print("현재개수:",장바구니개수)
# 에러난 이유는 위에서 장바구니에 추가가 안되어있음!

장바구니.append("팝콘")
장바구니.append("콜라")
장바구니.append("나쵸")
print(장바구니)

장바구니개수 = len(장바구니)
print("현재개수: ",장바구니개수)

# 추가되는 데이터는 항상 뒤쪽에 들어간다? O
# 코드는 항상 위에서 아래로 실행된다? O

# 위에 코드들에 문제점은 중복이다! 함수가 해결책인것인가..

# 삭제
print("삭제 전에는 무조건 확인",장바구니)

# 가글 삭제
# remove(값)
장바구니.remove("가글")
print(장바구니)

# 팝콘 삭제!
장바구니.remove("팝콘")
print(장바구니)

# 이미 삭제되었거나 없는 값이면 어떤 결과?
# 데이터가 없으면 에러가 발생한다. 이럴때는 먼저 물어봐 줘야 한다. 프로그램이 중간에 멈춰버리기 때문에!
# 먼저 데이터가 있는지 확인
# 장바구니 리스트에 팝콘이 있니?
# in 연산자 있으면 True, 없으면 False 
확인 = "팝콘" in 장바구니
print(확인)

if 확인 :
    장바구니.remove("팝콘")
    print(장바구니)
else:
    print("입력한 데이터가 없습니다!")

