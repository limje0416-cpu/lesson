# 고객추가 프로그램 만들기
#
# --- 고객 추가 프로그램 ---
#  1. 고객 추가
#  2. 고객 삭제
#  0. 종료!
#  메뉴>

# 0을 누르지 않으면 프로그램은 계속 메뉴를 출력함!
고객이름목록 = []
# 1번을 눌렀을 때 고객이름목록에 고객 이름을입력받아서
# 추가하는 코드를 작성하시오!
while True:
    print("---고객 추가 프로그램---")
    print("1. 고객 추가")   
    print("2. 고객 삭제")
    print("0. 종료!")
    print("메뉴 > ")
    메뉴 = int(input())
# 이건 지금 계속 반복만 하니까 멈추는 조건을 주어야함!
    if 메뉴 == 0:
        break
    elif 메뉴 ==1:
        추가이름 = input("고객이름을 추가하세요: ")
        고객이름목록.append(추가이름)
        print(고객이름목록)
print("종료!")

